NAVY   = RGBColor(0x1B, 0x4F, 0x8A)
BLUE2  = RGBColor(0x2E, 0x75, 0xB6)
GRAY   = RGBColor(0x44, 0x44, 0x41)
WHITE  = RGBColor(0xFF, 0xFF, 0xFF)
LGRAY  = RGBColor(0xEB, 0xF5, 0xFB)

def set_cell_bg(cell, hex_color):
    tc   = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd  = OxmlElement("w:shd")
    shd.set(qn("w:val"),   "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"),  hex_color)
    tcPr.append(shd)

def set_cell_border(cell):
    tc   = cell._tc
    tcPr = tc.get_or_add_tcPr()
    borders = OxmlElement("w:tcBorders")
    for side in ["top","left","bottom","right"]:
        el = OxmlElement(f"w:{side}")
        el.set(qn("w:val"),   "single")
        el.set(qn("w:sz"),    "4")
        el.set(qn("w:color"), "9E9E9E")
        borders.append(el)
    tcPr.append(borders)

def para(doc, text, bold=False, italic=False, size=11,
         color=None, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
         space_after=8, space_before=0, font="Times New Roman"):
    p  = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.space_after  = Pt(space_after)
    p.paragraph_format.space_before = Pt(space_before)
    run = p.add_run(text)
    run.font.name   = font
    run.font.size   = Pt(size)
    run.font.bold   = bold
    run.font.italic = italic
    if color:
        run.font.color.rgb = color
    return p

def heading(doc, text, level=1, size=None, color=NAVY):
    sizes = {1: 16, 2: 13, 3: 11}
    sz    = size or sizes.get(level, 11)
    p     = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(14 if level == 1 else 10)
    p.paragraph_format.space_after  = Pt(6)
    run = p.add_run(text)
    run.font.name  = "Arial"
    run.font.size  = Pt(sz)
    run.font.bold  = True
    run.font.color.rgb = color
    return p

def add_figure(doc, filename, caption, width=6.0):
    path = os.path.join(FIG_DIR, filename)
    if os.path.exists(path):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run()
        run.add_picture(path, width=Inches(width))
    else:
        para(doc, f"[Figure not found: {filename}]",
             italic=True, color=GRAY)
    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.space_after = Pt(14)
    r = cap.add_run(caption)
    r.font.name   = "Times New Roman"
    r.font.size   = Pt(9)
    r.font.italic = True
    r.font.color.rgb = GRAY

def rule(doc):
    """Horizontal divider paragraph."""
    p    = doc.add_paragraph()
    pPr  = p._p.get_or_add_pPr()
    pb   = OxmlElement("w:pBdr")
    bot  = OxmlElement("w:bottom")
    bot.set(qn("w:val"),   "single")
    bot.set(qn("w:sz"),    "6")
    bot.set(qn("w:color"), "1B4F8A")
    pb.append(bot)
    pPr.append(pb)
    p.paragraph_format.space_after = Pt(10)
    return p


