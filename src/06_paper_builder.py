def add_composite_table(doc, comp):
    """Table 1 — Seasonal composites by ENSO phase."""
    heading(doc, "Table 1. Kisalföld seasonal climate composites "
            "by ENSO phase (1960–2024)", level=3, color=BLUE2)

    headers = ["Season", "Phase", "N", "T anomaly (°C)",
               "P anomaly (mm)", "P anomaly (%)", "T sig.", "P sig."]
    col_w   = [Cm(1.8), Cm(2.2), Cm(0.9), Cm(2.4),
               Cm(2.4), Cm(2.2), Cm(1.5), Cm(1.5)]

    tbl = doc.add_table(rows=1, cols=len(headers))
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    tbl.style     = "Table Grid"

    # Header row
    hrow = tbl.rows[0]
    for i, (h, w) in enumerate(zip(headers, col_w)):
        cell = hrow.cells[i]
        cell.width = w
        set_cell_bg(cell, "1B4F8A")
        set_cell_border(cell)
        cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        p   = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(h)
        run.font.name  = "Arial"
        run.font.size  = Pt(8.5)
        run.font.bold  = True
        run.font.color.rgb = WHITE

    # Data rows
    shade = False
    for _, row in comp.iterrows():
        tr   = tbl.add_row()
        fill = "EBF5FB" if shade else "FFFFFF"
        vals = [
            row["season"], row["phase"].replace("_"," ").title(),
            str(row["n_months"]),
            f"{row['t_anom_c']:+.2f}",
            f"{row['p_anom_mm']:+.1f}",
            f"{row['p_anom_pct']:+.1f}",
            str(row["t_sig"]), str(row["p_sig"]),
        ]
        for i, (val, w) in enumerate(zip(vals, col_w)):
            cell = tr.cells[i]
            cell.width = w
            set_cell_bg(cell, fill)
            set_cell_border(cell)
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            p   = cell.paragraphs[0]
            p.alignment = (WD_ALIGN_PARAGRAPH.CENTER if i != 1
                           else WD_ALIGN_PARAGRAPH.LEFT)
            run = p.add_run(val)
            run.font.name = "Times New Roman"
            run.font.size = Pt(8.5)
        shade = not shade

    note = doc.add_paragraph()
    note.paragraph_format.space_after = Pt(12)
    r = note.add_run(
        "* p < 0.05,  ** p < 0.01 (two-sample t-test vs neutral years). "
        "Anomalies relative to neutral-phase monthly baseline, 1960–2024.")
    r.font.name   = "Times New Roman"
    r.font.size   = Pt(8)
    r.font.italic = True
    r.font.color.rgb = GRAY


